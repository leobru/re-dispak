def main():
    if len(sys.argv) == 1:
        for k, (f, what, _, _) in EDITS.items():
            print(k, f, what)
        return
    for k in sys.argv[1:]:
        f, what, new, old = EDITS[k]
        text = open(f, encoding="utf-8").read()
        if text.count(new) != 1:
            sys.exit(f"{k}: фрагмент не найден однозначно в {f}")
        open(f, "w", encoding="utf-8").write(text.replace(new, old))
        print(f"откатано {k}: {what}")


if __name__ == "__main__":
    main()
